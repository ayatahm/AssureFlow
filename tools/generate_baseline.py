#!/usr/bin/env python
"""Freeze a conformance baseline for a rule set.

    python tools/generate_baseline.py seed_demo/ruleset_demo.json -o seed_demo/baseline_demo.json

Each case records triage answers and the expected classification, routing,
per-control Keep/Skip + level + asked, and the ordered question list.

IMPORTANT: a baseline generated by this engine is a *regression* baseline — it
freezes today's behaviour. For approved private content the expected results
must come from the approved source logic (e.g. the workbook's own outputs),
supplied with ``--expected-from`` as a JSON list of {"answers", "expected"}
cases; this tool then only validates and normalises that file. Private
baselines live in private_data/baseline/ and are never committed.
"""
import argparse
import hashlib
import itertools
import json
import random

import _bootstrap  # noqa: F401

from apps.engine.engine import evaluate  # noqa: E402

FORMAT = "assureflow-baseline-v1"


def load_config(path):
    # loader.file_to_engine_config imports Django models; replicate the pure mapping here.
    data = json.loads(open(path, encoding="utf-8").read())
    return data, {
        "version": data["version"],
        "triage_questions": [{"code": q["code"], "kind": q["kind"], "options": q.get("options", [])}
                             for q in data["triage_questions"]],
        "classification": data["classification"],
        "routing": data.get("routing", []),
        "gates": [{"code": g["code"], "skip_when": g["skip_when"], "note": g.get("note", "")} for g in data["gates"]],
        "controls": [{"code": c["code"], "gates": c.get("gates", []), "levels": c["levels"],
                      "questions": c.get("questions", [])} for c in data["controls"]],
        "always_ask": [q["code"] for q in data["assessment_questions"] if q.get("always_ask")],
        "question_order": [q["code"] for q in data["assessment_questions"]],
    }


def all_answer_sets(cfg):
    domains = []
    for q in cfg["triage_questions"]:
        domains.append([(q["code"], v) for v in (("YES", "NO") if q["kind"] == "YES_NO" else q["options"])])
    for combo in itertools.product(*domains):
        yield dict(combo)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ruleset")
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("--sample", type=int, default=120, help="Number of sampled cases (0 = all combinations).")
    parser.add_argument("--seed", type=int, default=20260927)
    parser.add_argument("--expected-from", help="Externally produced expected results (approved source logic).")
    args = parser.parse_args()

    raw = open(args.ruleset, "rb").read()
    data, cfg = load_config(args.ruleset)
    if args.expected_from:
        cases = json.loads(open(args.expected_from, encoding="utf-8").read())
        source = "external"
    else:
        everything = list(all_answer_sets(cfg))
        if args.sample and args.sample < len(everything):
            rng = random.Random(args.seed)
            chosen = [everything[0], everything[-1]] + rng.sample(everything[1:-1], args.sample - 2)
        else:
            chosen = everything
        cases = [{"answers": a, "expected": evaluate(cfg, a).as_dict()} for a in chosen]
        source = "engine-regression"
    out = {
        "format": FORMAT,
        "ruleset_version": data["version"],
        "ruleset_sha256": hashlib.sha256(raw).hexdigest(),
        "source": source,
        "synthetic": bool(data.get("synthetic")),
        "cases": cases,
    }
    with open(args.output, "w", encoding="utf-8") as fh:
        json.dump(out, fh, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
        fh.write("\n")
    print(f"Wrote {len(cases)} cases ({source}) to {args.output}")


if __name__ == "__main__":
    main()
